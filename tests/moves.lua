local Session = require("pocketchess_session")
local Puzzles = require("pocketchess_puzzles")
local state = { entries = {} }
local game = Session.new(Puzzles, state)
assert(game.index == 1 and game.side == "w")
assert(game:hint() == "e7")
assert(game:play("e7e7") == "illegal")
local wrong = game.step.legal:match(" (%S+) ")
if wrong == game.step.move then wrong = game.step.legal:match(" %S+ (%S+) ") end
assert(game:play(wrong) == "incorrect")
assert(game.stage == 1 and not state.entries[game.puzzle.id])
assert(game:play("e7e8") == "correct")
assert(game.solved and not game.revealed and game:hint() == nil)
assert(game:reveal() == nil)
game:retry()
assert(game.stage == 1 and game.solved and not game.revealed)
assert(not game:navigate(-1))
assert(game:navigate(1) and game.index == 2)
assert(game:reveal() ~= nil and game.revealed and not game.solved)
assert(game:navigate(-1) and game.solved)
assert(game:navigate(1) and game.revealed)
game:retry()
assert(game.stage == 1 and not game.revealed and not game.solved)
