"""Compile verified standard-chess puzzle positions for the offline Lua runtime."""
import argparse
import csv
import json
from pathlib import Path
import re

import chess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "lichess-v0.1.csv"
OUTPUT = ROOT / "pocketchess.koplugin" / "pocketchess_puzzles.lua"


def compile_puzzle(row):
    puzzle_id = row["PuzzleId"]
    if not re.fullmatch("[A-Za-z0-9]{5}", puzzle_id):
        raise ValueError(f"Invalid puzzle ID {puzzle_id!r}")
    board = chess.Board(row["FEN"])
    moves = row["Moves"].split()
    if not board.is_valid() or len(moves) < 2 or len(moves) % 2:
        raise ValueError(f"{puzzle_id}: invalid starting position or line length")
    steps = []
    for ply, uci in enumerate(moves):
        move = chess.Move.from_uci(uci)
        if move not in board.legal_moves:
            raise ValueError(f"{puzzle_id}: illegal move {uci} at ply {ply}")
        if ply % 2:
            steps.append(dict(
                fen=board.fen(), move=uci, san=board.san(move),
                legal=" " + " ".join(sorted(m.uci() for m in board.legal_moves)) + " ",
            ))
        elif ply:
            steps[-1]["reply"] = board.san(move)
        board.push(move)
    steps.append(dict(fen=board.fen()))
    return dict(id=puzzle_id, rating=int(row["Rating"]), steps=steps)


def render(source):
    with source.open(newline="", encoding="utf-8") as stream:
        puzzles = [compile_puzzle(row) for row in csv.DictReader(stream)]
    if not puzzles or len({puzzle["id"] for puzzle in puzzles}) != len(puzzles):
        raise ValueError("Puzzle IDs must be unique and the pack must contain puzzles")
    out = ["-- Generated by scripts/build_puzzles.py.", "return {"]
    for puzzle in puzzles:
        out.append(f'    {{ id = "{puzzle["id"]}", rating = {puzzle["rating"]}, steps = {{')
        for step in puzzle["steps"]:
            fields = ", ".join(f"{key} = {json.dumps(value)}" for key, value in step.items())
            out.append(f"        {{ {fields} }},")
        out.append("    } },")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(SOURCE)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != generated:
            parser.exit(1, "Puzzle pack is out of date. Run scripts/build_puzzles.py.\n")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")


if __name__ == "__main__":
    main()
